const LOWER = new Map(Object.entries(TYPO_LINE_FACTORS).map(([k, v]) => [k.toLowerCase(), v]));

/** First family of a CSS font-family list, without quotes. */
export function primaryFamily(css?: string): string {
  if (!css) return '';
  return css.split(',')[0].trim().replace(/^['"]|['"]$/g, '');
}

/** Single line height as a multiple of the font size, as Publisher computes it. */
export function lineFactor(css?: string): number {
  const fam = primaryFamily(css).toLowerCase();
  const exact = LOWER.get(fam);
  if (exact) return exact;
  // "Twinkl ExtraBold" -> "Twinkl", "Arial Narrow Bold" -> "Arial Narrow"
  const base = fam.replace(/\s+(extra|semi|ultra|demi)?\s*(bold|light|black|medium|thin|italic|regular)\b.*$/, '');
  return LOWER.get(base) ?? 1.2;
}

const SERIF = /times|georgia|garamond|antiqua|cambria|bookman|baskerville|bodoni|schoolbook|constantia|palatino|rockwell|traditional arabic|simplified arabic|sakkal|majalla|typesetting|naskh|amiri/i;
const SCRIPT = /script|hand|brush|corsiva|chancery|kristen|comic|twinkl|segoe print|ink free|gabriola|curlz|jokerman/i;

/** CSS family list with a sensible generic fallback. */
export function cssFontFamily(name: string): string {
  const n = name.trim();
  if (!n) return 'Inter, sans-serif';
  const quoted = /[^A-Za-z-]/.test(n) ? `"${n}"` : n;
  // School fonts (Twinkl, Sassoon…) fall back to a rounded humanist face of similar width
  if (/twinkl|sassoon/i.test(n)) return `${quoted}, Candara, "Comic Sans MS", cursive`;
  if (/^comic sans/i.test(n)) return `${quoted}, "Segoe Print", cursive`;
  if (SCRIPT.test(n)) return `${quoted}, "Comic Sans MS", cursive`;
  if (SERIF.test(n)) return `${quoted}, "Times New Roman", serif`;
  return `${quoted}, Arial, sans-serif`;
}

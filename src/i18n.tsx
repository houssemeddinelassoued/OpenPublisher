const DICTS: Record<Lang, Dict> = { fr, en, ar };
const LANG_KEY = 'op.lang';

export type TFn = (key: string, vars?: Record<string, string | number>) => string;

interface I18nCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: TFn;
  dir: 'ltr' | 'rtl';
  locale: string;
  fmtDate: (iso: string | number, withTime?: boolean) => string;
}

const Ctx = createContext<I18nCtx | null>(null);

function initialLang(): Lang {
  try {
    const s = localStorage.getItem(LANG_KEY) as Lang | null;
    if (s && DICTS[s]) return s;
  } catch {
    /* ignore */
  }
  const nav = (navigator.language || 'fr').slice(0, 2);
  return nav === 'en' || nav === 'ar' ? nav : 'fr';
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  const dir = lang === 'ar' ? 'rtl' : 'ltr';
  const locale = lang === 'fr' ? 'fr-FR' : lang === 'ar' ? 'ar-TN' : 'en-GB';

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
  }, [lang, dir]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(LANG_KEY, l);
    } catch {
      /* ignore */
    }
  }, []);

  const t = useCallback<TFn>(
    (key, vars) => {
      let s = DICTS[lang][key] ?? fr[key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
      return s;
    },
    [lang]
  );

  const fmtDate = useCallback(
    (iso: string | number, withTime = true) => {
      const d = new Date(iso);
      return withTime
        ? d.toLocaleString(locale, { day: 'numeric', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit' })
        : d.toLocaleDateString(locale, { day: 'numeric', month: 'long', year: 'numeric' });
    },
    [locale]
  );

  const value = useMemo(() => ({ lang, setLang, t, dir, locale, fmtDate }) as I18nCtx, [lang, setLang, t, dir, locale, fmtDate]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18nCtx {
  const c = useContext(Ctx);
  if (!c) throw new Error('useI18n outside provider');
  return c;
}
